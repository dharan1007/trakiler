-- FORM backend schema — dedicated Supabase/Postgres project only.
-- Private-by-default training data; explicit public projection for opt-in Club ranking.

create schema if not exists private;

create table if not exists public.form_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'FORM athlete' check (char_length(display_name) between 1 and 30),
  goal text not null default 'general' check (goal in ('general','muscle','strength','recomp')),
  experience text not null default 'beginner' check (experience in ('beginner','intermediate','advanced')),
  training_days integer not null default 3 check (training_days between 2 and 6),
  session_minutes integer not null default 60 check (session_minutes between 25 and 180),
  equipment text not null default 'gym' check (equipment in ('gym','basic')),
  club_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.form_legal_acceptance (
  user_id uuid primary key references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  accepted_at timestamptz not null default now()
);

create table if not exists public.form_workouts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id text not null check (char_length(client_id) between 1 and 120),
  program_name text not null default '',
  day_name text not null default '',
  ended_at timestamptz not null,
  elapsed_sec integer not null default 0 check (elapsed_sec between 0 and 86400),
  completed_sets integer not null default 0 check (completed_sets between 0 and 100),
  total_sets integer not null default 0 check (total_sets between 0 and 100),
  total_volume_kg numeric(14,2) not null default 0 check (total_volume_kg between 0 and 5000000),
  notes text not null default '' check (char_length(notes) <= 4000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, client_id)
);

create table if not exists public.form_workout_sets (
  id bigint generated by default as identity primary key,
  workout_id uuid not null references public.form_workouts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  set_index integer not null check (set_index between 1 and 100),
  exercise_id text not null check (char_length(exercise_id) between 1 and 100),
  exercise_name text not null default '' check (char_length(exercise_name) <= 100),
  weight_kg numeric(9,2) not null default 0 check (weight_kg between 0 and 2000),
  reps integer not null default 0 check (reps between 0 and 500),
  rir numeric(4,1) not null default 0 check (rir between 0 and 10),
  e1rm_kg numeric(10,2) generated always as (weight_kg * (1 + least(reps, 12)::numeric / 30)) stored,
  created_at timestamptz not null default now(),
  unique(workout_id, set_index)
);

create table if not exists public.form_body_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  log_date date not null default current_date,
  weight_kg numeric(6,2) check (weight_kg between 20 and 400),
  bodyfat_pct numeric(5,2) check (bodyfat_pct between 2 and 70),
  note text not null default '' check (char_length(note) <= 500),
  created_at timestamptz not null default now(),
  unique(user_id, log_date)
);

create table if not exists public.form_measurements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  log_date date not null default current_date,
  waist_cm numeric(6,2), chest_cm numeric(6,2), shoulders_cm numeric(6,2), hips_cm numeric(6,2),
  left_arm_cm numeric(6,2), right_arm_cm numeric(6,2), left_thigh_cm numeric(6,2), right_thigh_cm numeric(6,2),
  left_calf_cm numeric(6,2), right_calf_cm numeric(6,2),
  created_at timestamptz not null default now(),
  unique(user_id, log_date),
  check (coalesce(waist_cm,1) between 1 and 300 and coalesce(chest_cm,1) between 1 and 300 and coalesce(shoulders_cm,1) between 1 and 300 and coalesce(hips_cm,1) between 1 and 300 and coalesce(left_arm_cm,1) between 1 and 300 and coalesce(right_arm_cm,1) between 1 and 300 and coalesce(left_thigh_cm,1) between 1 and 300 and coalesce(right_thigh_cm,1) between 1 and 300 and coalesce(left_calf_cm,1) between 1 and 300 and coalesce(right_calf_cm,1) between 1 and 300)
);

create table if not exists public.form_daily_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_date date not null default current_date,
  bodyweight_kg numeric(6,2) not null check (bodyweight_kg between 30 and 250),
  steps integer not null default 0 check (steps between 0 and 100000),
  active_minutes integer not null default 0 check (active_minutes between 0 and 600),
  completed_sets integer not null default 0 check (completed_sets between 0 and 80),
  total_volume_kg numeric(12,2) not null default 0 check (total_volume_kg between 0 and 1000000),
  streak_days integer not null default 1 check (streak_days between 1 and 3650),
  activity_score numeric(8,1) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, activity_date)
);

create table if not exists public.form_public_daily_leaderboard (
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_date date not null,
  display_name text not null,
  steps integer not null,
  active_minutes integer not null,
  completed_sets integer not null,
  total_volume_kg numeric(12,2) not null,
  streak_days integer not null,
  activity_score numeric(8,1) not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, activity_date)
);

create index if not exists form_workouts_user_date_idx on public.form_workouts(user_id, ended_at desc);
create index if not exists form_sets_user_exercise_idx on public.form_workout_sets(user_id, exercise_id, created_at desc);
create index if not exists form_body_user_date_idx on public.form_body_logs(user_id, log_date desc);
create index if not exists form_measure_user_date_idx on public.form_measurements(user_id, log_date desc);
create index if not exists form_daily_activity_date_score_idx on public.form_daily_activity(activity_date, activity_score desc);
create index if not exists form_public_leaderboard_date_score_idx on public.form_public_daily_leaderboard(activity_date, activity_score desc);


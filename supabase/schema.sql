create or replace function private.form_activity_score(p_sets integer,p_volume numeric,p_bodyweight numeric,p_steps integer,p_minutes integer,p_streak integer) returns numeric language sql immutable set search_path='' as $$
  select round((least(greatest(coalesce(p_sets,0),0),40)*4.0 + least(greatest(coalesce(p_volume,0)/greatest(coalesce(p_bodyweight,75),40),0),220)*0.55 + least(greatest(coalesce(p_minutes,0),0),180)*0.55 + least(greatest(coalesce(p_steps,0)/1000.0,0),25)*3.0 + log(2,least(greatest(coalesce(p_streak,0),0),365)+1)*12.0)::numeric,1)
$$;

create or replace function private.form_activity_before_write() returns trigger language plpgsql security invoker set search_path='' as $$
declare v_prev integer;
begin
  if new.user_id is distinct from (select auth.uid()) then raise exception 'user_id must match authenticated user'; end if;
  select a.streak_days into v_prev from public.form_daily_activity a where a.user_id=new.user_id and a.activity_date=new.activity_date-1;
  if tg_op='INSERT' or new.activity_date is distinct from old.activity_date then new.streak_days:=coalesce(v_prev,0)+1; end if;
  new.activity_score:=private.form_activity_score(new.completed_sets,new.total_volume_kg,new.bodyweight_kg,new.steps,new.active_minutes,new.streak_days);
  new.updated_at:=now(); return new;
end; $$;

create or replace function private.form_publish_leaderboard() returns trigger language plpgsql security definer set search_path='' as $$
declare v_uid uuid:=(select auth.uid()); v_name text; v_public boolean;
begin
  if v_uid is null or new.user_id is distinct from v_uid then raise exception 'unauthorized FORM Club publish'; end if;
  select p.display_name,p.club_public into v_name,v_public from public.form_profiles p where p.user_id=v_uid;
  if coalesce(v_public,false)=false then
    delete from public.form_public_daily_leaderboard where user_id=v_uid;
    return new;
  end if;
  insert into public.form_public_daily_leaderboard(user_id,activity_date,display_name,steps,active_minutes,completed_sets,total_volume_kg,streak_days,activity_score,updated_at)
  values(new.user_id,new.activity_date,v_name,new.steps,new.active_minutes,new.completed_sets,new.total_volume_kg,new.streak_days,new.activity_score,now())
  on conflict(user_id,activity_date) do update set display_name=excluded.display_name,steps=excluded.steps,active_minutes=excluded.active_minutes,completed_sets=excluded.completed_sets,total_volume_kg=excluded.total_volume_kg,streak_days=excluded.streak_days,activity_score=excluded.activity_score,updated_at=now();
  return new;
end; $$;

create or replace function private.form_profile_privacy_sync() returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.user_id is distinct from (select auth.uid()) then raise exception 'unauthorized profile update'; end if;
  new.updated_at:=now();
  if new.club_public=false then delete from public.form_public_daily_leaderboard where user_id=new.user_id;
  elsif old.display_name is distinct from new.display_name then update public.form_public_daily_leaderboard set display_name=new.display_name,updated_at=now() where user_id=new.user_id; end if;
  return new;
end; $$;

